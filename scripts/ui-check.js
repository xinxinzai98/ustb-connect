async (page) => {
  const checks=[];const errors=[];page.on('pageerror',error=>errors.push(error.message));
  const verify=(condition,message)=>{if(!condition)throw new Error(message);checks.push(message);};
  const status=()=>page.evaluate(()=>window.bkql.invoke('status'));
  const initial=await status();
  if(initial.platform==='darwin')verify(initial.ui.tray.size.width===16&&initial.ui.tray.scales.includes(2)&&initial.ui.tray.template,'Mac 菜单栏图标按 16 点和 Retina 双倍率模板加载');
  const idle=()=>page.waitForFunction(async()=>!(await window.bkql.invoke('status')).busy);
  if((await status()).running){await page.locator('[data-page=overview]').click();await page.getByRole('button',{name:'停止模拟监测',exact:true}).click();}
  await page.locator('[data-page=wifi]').click();
  await page.locator('#wifi-form [name=ssid]').fill('Friends Wi-Fi');
  await page.locator('#wifi-form [name=security]').selectOption('wpa2');
  await page.locator('#wifi-form [name=password]').fill('DEMO-ONLY-WIFI-wrong');
  await page.getByRole('button',{name:'保存无线配置',exact:true}).click();
  await page.waitForFunction(async()=>(await window.bkql.invoke('status')).wifi.ssid==='Friends Wi-Fi');
  verify((await status()).wifi.verified===false,'自定义无线名称已保存，未把保存当作验证');
  const verifyWireless=async()=>{await page.getByRole('button',{name:'连接并验证',exact:true}).click();await page.locator('#confirm-dialog [data-action=confirm-action]').click();await idle();};
  await verifyWireless();verify((await status()).wifi.validation.state==='authRejected','错误无线密码显示验证失败');
  await page.locator('#wifi-form [name=password]').fill('DEMO-ONLY-WIFI-CORRECT');
  await page.getByRole('button',{name:'保存无线配置',exact:true}).click();await idle();
  await verifyWireless();verify((await status()).wifi.verified===true,'正确无线配置通过模拟连接与 IP 验证');
  verify(await page.locator('#wifi-form [name=password]').inputValue()==='','保存后的无线密码不回填');
  verify(!JSON.stringify(await status()).includes('DEMO-ONLY-WIFI-CORRECT'),'无线密码不进入状态接口');
  await page.evaluate(()=>window.scrollTo(0,0));await page.screenshot({path:'output/playwright/wifi.png'});
  await page.locator('[data-page=accounts]').click();
  if(!(await page.locator('#account-dialog').isVisible()))await page.getByTitle('编辑账号').first().click();
  if(await page.locator('#account-dialog').isVisible()){
    verify(await page.locator('#account-form [name=password]').inputValue()==='','编辑账号不回填已保存密码');
    await page.locator('#account-form [name=label]').fill('主用校园账号 · 可编辑');
    await page.getByRole('button',{name:'保存账号',exact:true}).click();
    await page.waitForFunction(()=>!document.querySelector('#account-dialog').open);
  }
  await page.locator('[data-page=accounts]').click();
  verify((await status()).accounts[0].label.includes('可编辑'),'账号备注已保存');
  await page.getByRole('button',{name:'添加账号',exact:true}).click();
  await page.locator('#account-form [name=label]').fill('临时演练账号');
  await page.locator('#account-form [name=username]').fill('demo_temporary');
  await page.locator('#account-form [name=password]').fill('DEMO-ONLY-TEMPORARY');
  await page.getByRole('button',{name:'保存账号',exact:true}).click();
  await page.waitForFunction(async()=>(await window.bkql.invoke('status')).accounts.length===3);
  const saved=await status();verify(!JSON.stringify(saved).includes('DEMO-ONLY-TEMPORARY'),'状态接口不返回账号密码');
  await page.getByTitle('移除账号').last().click();
  await page.locator('#confirm-dialog [data-action=confirm-action]').click();
  await page.waitForFunction(async()=>(await window.bkql.invoke('status')).accounts.length===2);
  checks.push('账号添加、保存与确认移除完成');
  await page.screenshot({path:'output/playwright/accounts.png',fullPage:true});
  await page.locator('[data-page=settings]').click();
  for(const [name,value] of Object.entries({checkInterval:15,confirmInterval:3,failureThreshold:2,loginCooldown:120,statsInterval:60}))await page.locator(`#settings-form [name=${name}]`).fill(String(value));
  await page.locator('#settings-form [name=startOnBoot]').check();
  await page.getByRole('button',{name:'保存设置',exact:true}).click();
  await page.waitForFunction(async()=>(await window.bkql.invoke('status')).settings.checkInterval===15);
  const policy=(await status()).settings;verify(policy.startOnBoot&&policy.confirmInterval===3&&policy.loginCooldown===120,'检测间隔、冷却和演练自启开关已保存');
  await page.evaluate(()=>window.scrollTo(0,0));await page.screenshot({path:'output/playwright/settings.png'});
  await page.locator('[data-page=overview]').click();
  const recoveryAfter=(await status()).time;
  await page.getByRole('combobox',{name:'选择模拟场景'}).selectOption('campusOffline');await idle();
  await page.getByRole('button',{name:'启动模拟监测',exact:true}).click();
  await page.waitForFunction(async after=>{const s=await window.bkql.invoke('status');return !s.busy&&s.logs.some(x=>x.code==='recovered'&&x.time>=after&&x.detail.ipv6==='online')&&s.ipv4==='online'&&s.ipv6==='online';},recoveryAfter,{timeout:20000});
  checks.push('模拟校园注销后自动重新认证并独立核验 IPv6');
  await page.getByRole('button',{name:'停止模拟监测',exact:true}).click();
  verify((await status()).running===false,'暂停入口立即关闭自动监测');
  await page.getByRole('button',{name:'启动模拟监测',exact:true}).click();
  await page.locator('[data-action=stop-all]').click();
  await page.waitForFunction(async()=>!(await window.bkql.invoke('status')).running);
  checks.push('停止全部监测入口可停止模拟监测');
  await page.getByRole('combobox',{name:'选择模拟场景'}).selectOption('healthy');await idle();
  verify((await page.locator('.metric-value').allTextContents()).join(' ').includes('18.66'),'余额与 IPv4 / IPv6 用量显示正常');
  verify((await page.locator('.metric-value').allTextContents()).join(' ').includes('MB'),'用量保持校方 MB 单位');
  await page.getByRole('combobox',{name:'选择模拟场景'}).selectOption('unmanagedAccount');await idle();
  verify((await status()).activeId===null&&(await page.locator('.metric-value').allTextContents()).every(x=>x.trim()==='—'),'身份变更后不显示旧账号余额');
  const beforeUnknown=(await status()).lastLoginAt;
  await page.getByRole('combobox',{name:'选择模拟场景'}).selectOption('authUnavailable');await idle();
  await page.getByRole('button',{name:'启动模拟监测',exact:true}).click();await idle();
  verify((await status()).lastLoginAt===beforeUnknown,'认证未知且无拦截证据时不追加认证');
  await page.locator('[data-action=stop-all]').click();
  await page.getByRole('combobox',{name:'选择模拟场景'}).selectOption('healthy');await idle();
  await page.screenshot({path:'output/playwright/overview.png',fullPage:true});
  await page.locator('[data-page=diagnostics]').click();
  verify((await page.locator('.full-events').innerText()).includes('检测完成'),'逐轮结果已出现在运行记录');
  await page.screenshot({path:'output/playwright/logs.png',fullPage:true});
  await page.locator('#switch-mode').click();
  await page.waitForFunction(()=>document.querySelector('#toast').textContent.includes('隔离测试'));
  verify((await status()).mode==='simulation','隔离预览阻止连接真实系统后台');
  await page.locator('[data-page=overview]').click();await page.setViewportSize({width:1020,height:720});
  verify(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),'最小窗口无整页横向溢出');
  await page.screenshot({path:'output/playwright/minimum-window.png',fullPage:true});
  await page.setViewportSize({width:1240,height:818});
  verify(errors.length===0,'页面执行无未捕获异常');
  return {checks,errors,mode:(await status()).mode};
}
